/**
 * Ship the Vite bundle into the HarmonyOS module.
 *
 * ArkWeb loads the page from `resource://rawfile/www/`, so the build has to use
 * relative asset URLs (`base: './'`) and the service worker is dropped: nothing
 * serves it from that scheme.
 *
 * Usage:
 *   node scripts/harmony-sync.mjs [--server http://192.168.1.20:8787]
 */

import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const STAGING = path.join(ROOT, '.harmony-dist');
const WWW = path.join(ROOT, 'harmony/entry/src/main/resources/rawfile/www');
const SERVER_KEY = 'stay-tuned:server';

function parseArgs(argv) {
  const args = { server: '' };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--server') {
      args.server = String(argv[index + 1] || '');
      index += 1;
    }
  }
  return args;
}

function run(command, args) {
  const result = spawnSync(command, args, { cwd: ROOT, stdio: 'inherit', env: process.env });
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(' ')} 失败，退出码 ${result.status}`);
  }
}

function buildBundle() {
  rmSync(STAGING, { recursive: true, force: true });
  run(process.platform === 'win32' ? 'npx.cmd' : 'npx', [
    'vite',
    'build',
    '--base',
    './',
    '--outDir',
    path.relative(ROOT, STAGING),
    '--emptyOutDir',
  ]);
}

/**
 * A first-run hint for the companion Node server. The app already lets the user
 * change this in settings; pre-seeding it just saves typing on a new device.
 */
function writeNativeConfig(server) {
  if (!server) return;
  const target = path.join(STAGING, 'native-config.js');
  const script = `/* generated by scripts/harmony-sync.mjs */
try {
  var key = '${SERVER_KEY}';
  if (!localStorage.getItem(key)) localStorage.setItem(key, '${server.replace(/'/g, "\\'")}');
} catch (error) {
  /* private mode: the settings screen still works */
}
`;
  writeFileSync(target, script, 'utf8');

  const indexFile = path.join(STAGING, 'index.html');
  const html = readFileSync(indexFile, 'utf8').replace(
    /<head>/i,
    '<head>\n    <script src="./native-config.js"></script>',
  );
  writeFileSync(indexFile, html, 'utf8');
}

function publish() {
  rmSync(WWW, { recursive: true, force: true });
  mkdirSync(path.dirname(WWW), { recursive: true });
  cpSync(STAGING, WWW, { recursive: true });
  // No http origin, no service worker.
  rmSync(path.join(WWW, 'sw.js'), { force: true });
  rmSync(STAGING, { recursive: true, force: true });
}

function main() {
  const { server } = parseArgs(process.argv.slice(2));
  if (!existsSync(path.join(ROOT, 'harmony/entry'))) {
    throw new Error('找不到 harmony/entry，请先创建鸿蒙工程。');
  }
  console.log('[harmony] 构建前端资源（相对路径 base）…');
  buildBundle();
  writeNativeConfig(server);
  console.log('[harmony] 复制到 entry/src/main/resources/rawfile/www …');
  publish();
  console.log('[harmony] 完成。下一步：npm run harmony:hap');
}

main();
